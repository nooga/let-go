// loweredCoreNamespaces are the embedded namespaces `lg compile -lowered-core`
// lowers to Go and links. The set is deliberately short: a namespace whose
// macros expand to its own symbols does not survive lowering yet (#1098), and
// the compiler's own ir.* namespaces are most of the lowering time and are
// not called by a compiled program.
var loweredCoreNamespaces = []string{"core", "walk"}

// loweredCoreDirName is the directory, inside the one lg generates into, that
// holds the lowered core. Its packages are imported as <import-path>/lgcore/….
const loweredCoreDirName = "lgcore"

// loweredCoreStagePattern names the directory a tree is assembled in before
// it is renamed to lgcore/. The leading dot keeps the go command from reading
// it as a package directory.
const loweredCoreStagePattern = ".lgcore-stage-*"

const loweredCoreImportsFile = "lgcore_imports.go"

// lgbgenPackage lowers the core. It is run from the module being built, so it
// is the lgbgen of the let-go version that module links.
const lgbgenPackage = gomod.ModulePath + "/cmd/lgbgen"

// clearLoweredCore removes what an earlier -lowered-core build left in dir: the
// imports file, the tree, and any staging directory an interrupted build left
// behind. It runs before the program is written, on every build, so a kept
// -work directory reused without the flag does not go on linking the core.
// Only a tree lgbgen wrote is removed (it carries lgbgen's manifest); a
// program's own package under lgcore/ is left alone.
func clearLoweredCore(dir string) error {
	if err := os.Remove(filepath.Join(dir, loweredCoreImportsFile)); err != nil && !os.IsNotExist(err) {
		return err
	}
	stages, _ := filepath.Glob(filepath.Join(dir, loweredCoreStagePattern))
	for _, stage := range stages {
		if err := os.RemoveAll(stage); err != nil {
			return err
		}
	}
	target := filepath.Join(dir, loweredCoreDirName)
	if _, err := os.Stat(filepath.Join(target, genmanifest.TreeManifestName)); err != nil {
		return nil
	}
	return os.RemoveAll(target)
}

// lowerCoreInto puts the lowered core under dir/lgcore and blank-imports its
// packages into the program's main package, so their init() installs the
// native functions over the bytecode ones. dir must already sit in a Go
// module that requires let-go; importPath is dir's import path. readonly
// keeps the go command from editing a caller's go.mod.
//
// Any failure is an error. A build asked for the lowered core must not come
// out running bytecode.
func lowerCoreInto(dir, importPath string, readonly bool) error {
	// lgbgen runs with dir as its working directory, so a relative dir would
	// be resolved a second time there.
	dir, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	prefix := importPath + "/" + loweredCoreDirName
	target := filepath.Join(dir, loweredCoreDirName)
	// clearLoweredCore already removed an earlier build's tree, so anything
	// here now is a program package: a namespace whose first segment is
	// lgcore lowers to this same directory. It may be this program's, or one
	// an earlier build left in a kept directory; lg cannot tell which.
	if _, err := os.Stat(target); err == nil {
		return fmt.Errorf("-lowered-core needs %s for the lowered core, and a program package is already there (an lgcore.* namespace, from this build or left by an earlier one in this directory); rename the namespace, remove that directory, or build without the flag", target)
	}

	// The tree is assembled beside its final place and renamed in, so an
	// interrupted build never leaves a partial lgcore/ that the check above
	// would then take for a program package.
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	stage, err := os.MkdirTemp(dir, loweredCoreStagePattern)
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	tree := filepath.Join(stage, "tree")

	if cache, ok := loweredCoreCacheDir(dir, prefix, readonly); ok {
		if err := fillLoweredCoreCache(cache, dir, prefix, readonly); err != nil {
			return err
		}
		if err := os.CopyFS(tree, os.DirFS(cache)); err != nil {
			return fmt.Errorf("copying the lowered core from %s: %w", cache, err)
		}
	} else if err := lgbgenRunner(dir, prefix, tree, readonly); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("// Code generated by lg compile -lowered-core. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	for _, ns := range loweredCoreNamespaces {
		pkg := filepath.Join(tree, filepath.FromSlash(nsRelDir(ns)))
		if !dirExists(pkg) {
			return fmt.Errorf("lowering the core produced no package for %s", ns)
		}
		b.WriteString("\t_ " + strconv.Quote(prefix+"/"+nsRelDir(ns)) + "\n")
	}
	b.WriteString(")\n")
	if err := os.Rename(tree, target); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, loweredCoreImportsFile), []byte(b.String()), 0644)
}

// fillLoweredCoreCache makes cache hold a complete lowered tree, lowering it
// when the entry is absent or does not match its own manifest. A cache
// cleaner or an interrupted copy can leave a directory with files missing;
// reusing that would fail every later build with nothing pointing at the
// cache.
func fillLoweredCoreCache(cache, moduleDir, prefix string, readonly bool) error {
	if dirExists(cache) {
		if genmanifest.CheckTreeManifest(cache) == nil {
			return nil
		}
		if err := os.RemoveAll(cache); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(cache), 0755); err != nil {
		return err
	}
	// Lower beside the final place and rename, so an interrupted build
	// never leaves a partial tree under the cache key.
	tmp, err := os.MkdirTemp(filepath.Dir(cache), "tmp-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	out := filepath.Join(tmp, "tree")
	if err := lgbgenRunner(moduleDir, prefix, out, readonly); err != nil {
		return err
	}
	// Another build may have filled the entry meanwhile; its tree is as good.
	if err := os.Rename(out, cache); err != nil && genmanifest.CheckTreeManifest(cache) != nil {
		return err
	}
	return nil
}

// nsRelDir is the directory lgbgen writes a namespace's package to: dots
// become path separators and hyphens underscores.
func nsRelDir(ns string) string {
	return strings.ReplaceAll(strings.ReplaceAll(ns, ".", "/"), "-", "_")
}

// loweredCoreCacheDir names the cached tree for the let-go that moduleDir's
// module links and for this import prefix, or reports that this build must
// not cache.
//
// The key is the let-go version the go command resolves there, not this lg's
// own: with -module the caller's go.mod decides which let-go is linked, and
// lgbgen is run from that same module. A let-go replaced by a directory is
// never cached, since its source can change under one path.
func loweredCoreCacheDir(moduleDir, prefix string, readonly bool) (string, bool) {
	ref, ok := letgoResolver(moduleDir, readonly)
	if !ok {
		return "", false
	}
	base, err := os.UserCacheDir()
	if err != nil {
		return "", false
	}
	return filepath.Join(base, "let-go", "lowered-core", loweredCoreCacheKey(ref, prefix)), true
}

func loweredCoreCacheKey(letgoRef, prefix string) string {
	sum := sha256.Sum256([]byte(letgoRef + "\n" + prefix + "\n" + strings.Join(loweredCoreNamespaces, ",")))
	return hex.EncodeToString(sum[:8])
}

// letgoResolver reports the immutable module version of let-go that
// moduleDir builds against, as path@version; a test replaces it.
var letgoResolver = resolveLetGo

func resolveLetGo(moduleDir string, readonly bool) (string, bool) {
	args := []string{"list", "-m", "-json"}
	if readonly {
		args = append(args, "-mod=readonly")
	}
	cmd := exec.Command(gomod.GoToolPath(), append(args, gomod.ModulePath)...)
	cmd.Dir = moduleDir
	out, err := cmd.Output()
	if err != nil {
		return "", false
	}
	return letgoRefFrom(out)
}

// letgoRefFrom reads `go list -m -json` for let-go. A replacement wins over
// the required version, and one without a version is a directory.
func letgoRefFrom(listJSON []byte) (string, bool) {
	var m struct {
		Path, Version string
		Replace       *struct{ Path, Version string }
	}
	if err := json.Unmarshal(listJSON, &m); err != nil {
		return "", false
	}
	if m.Replace != nil {
		m.Path, m.Version = m.Replace.Path, m.Replace.Version
	}
	if m.Path == "" || m.Version == "" {
		return "", false
	}
	return m.Path + "@" + m.Version, true
}

// lgbgenRunner lowers the core into out; a test replaces it.
var lgbgenRunner = runLGBGen

func runLGBGen(moduleDir, prefix, out string, readonly bool) error {
	args := []string{"run", "-tags", "bootstrap"}
	if readonly {
		args = append(args, "-mod=readonly")
	}
	args = append(args, lgbgenPackage, "--target=go",
		"--ns", strings.Join(loweredCoreNamespaces, ","),
		"--import-prefix", prefix, out)
	cmd := exec.Command(gomod.GoToolPath(), args...)
	cmd.Dir = moduleDir
	cmd.Env = hostGoEnv(os.Environ())
	// lgbgen reports every namespace it compiles on stdout; only a failure is
	// worth showing.
	var output bytes.Buffer
	cmd.Stdout = &output
	cmd.Stderr = &output
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("lowering the core (go run %s): %w\n%s", lgbgenPackage, err, output.String())
	}
	return nil
}

// hostGoEnv is env with GOOS and GOARCH set to this machine's. lgbgen is a
// build tool that runs here; a cross-compiling GOOS=linux lg compile would
// otherwise have go run build it for the target and fail to execute it.
func hostGoEnv(env []string) []string {
	return append(append([]string(nil), env...), "GOOS="+runtime.GOOS, "GOARCH="+runtime.GOARCH)
}

func dirExists(path string) bool {
	fi, err := os.Stat(path)
	return err == nil && fi.IsDir()
}
